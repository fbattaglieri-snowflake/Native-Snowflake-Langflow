-- 1. Grant Task, Stream, and Alert creation & execution privileges to authorized roles
GRANT CREATE TASK, CREATE STREAM, CREATE ALERT
    ON SCHEMA SNOWFLAKE_LANGFLOW.CORE
    TO ROLE SNOWFLAKE_LANGFLOW_ADMIN_ROLE;

GRANT CREATE TASK, CREATE STREAM, CREATE ALERT
    ON SCHEMA SNOWFLAKE_LANGFLOW.CORE
    TO ROLE SNOWFLAKE_LANGFLOW_DEV_ROLE;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK, EXECUTE ALERT, EXECUTE MANAGED ALERT
    ON ACCOUNT
    TO ROLE SNOWFLAKE_LANGFLOW_ADMIN_ROLE;

GRANT EXECUTE TASK, EXECUTE MANAGED TASK, EXECUTE ALERT, EXECUTE MANAGED ALERT
    ON ACCOUNT
    TO ROLE SNOWFLAKE_LANGFLOW_DEV_ROLE;

-- 2. Durable Snowflake Trigger Registry Table (governed under SNOWFLAKE_LANGFLOW.CORE)
CREATE TABLE IF NOT EXISTS SNOWFLAKE_LANGFLOW.CORE.LANGFLOW_TRIGGER_REGISTRY (
    TRIGGER_ID VARCHAR(128) NOT NULL,
    FLOW_ID VARCHAR(128) NOT NULL,
    FLOW_SHORT_ID VARCHAR(32) NOT NULL,
    NODE_ID VARCHAR(128) NOT NULL,
    TRIGGER_COMPONENT VARCHAR(64) NOT NULL,
    TRIGGER_TYPE VARCHAR(64) NOT NULL,
    STATUS_MODE VARCHAR(32) NOT NULL,
    DATABASE_NAME VARCHAR(128) NOT NULL,
    SCHEMA_NAME VARCHAR(128) NOT NULL,
    PRIMARY_OBJECT_FQN VARCHAR(512) NOT NULL,
    SECONDARY_OBJECT_FQN VARCHAR(512),
    SOURCE_OBJECT_FQN VARCHAR(512),
    ACTIVE_ROLE VARCHAR(128) NOT NULL,
    CONFIG_JSON VARIANT,
    DDL_TEXT VARCHAR,
    CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (TRIGGER_ID)
);

-- 3. SPCS Internal Service Function for Scheduled Tasks, Stream Tasks, and Condition Alerts
-- Invokes SnowflakeLangflow's internal FastAPI batch endpoint without public egress or static tokens.
CREATE OR REPLACE FUNCTION SNOWFLAKE_LANGFLOW.CORE.RUN_LANGFLOW_FLOW(
    flow_id VARCHAR,
    trigger_payload VARIANT
)
RETURNS VARIANT
SERVICE = SNOWFLAKE_LANGFLOW.CORE.SNOWFLAKE_LANGFLOW_SERVICE
ENDPOINT = ui
MAX_BATCH_ROWS = 1
AS '/api/v1/snowflake/service-trigger';

-- 4. Grant USAGE on the Service Function to governed SnowflakeLangflow roles
GRANT USAGE ON FUNCTION SNOWFLAKE_LANGFLOW.CORE.RUN_LANGFLOW_FLOW(VARCHAR, VARIANT)
    TO ROLE SNOWFLAKE_LANGFLOW_ADMIN_ROLE;

GRANT USAGE ON FUNCTION SNOWFLAKE_LANGFLOW.CORE.RUN_LANGFLOW_FLOW(VARCHAR, VARIANT)
    TO ROLE SNOWFLAKE_LANGFLOW_DEV_ROLE;

GRANT USAGE ON FUNCTION SNOWFLAKE_LANGFLOW.CORE.RUN_LANGFLOW_FLOW(VARCHAR, VARIANT)
    TO ROLE SNOWFLAKE_LANGFLOW_VIEWER_ROLE;
