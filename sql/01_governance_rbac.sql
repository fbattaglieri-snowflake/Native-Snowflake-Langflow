-- 1. Create dedicated functional roles (Interactive Caller vs Technical Automation)
CREATE ROLE IF NOT EXISTS IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');
CREATE ROLE IF NOT EXISTS IDENTIFIER('<LANGFLOW_DEVELOPER_ROLE>');
CREATE ROLE IF NOT EXISTS IDENTIFIER('<LANGFLOW_VIEWER_ROLE>');
CREATE ROLE IF NOT EXISTS IDENTIFIER('<LANGFLOW_AUTOMATION_ROLE>');

-- 2. Database and Schema creation (without destructive OR REPLACE)
CREATE DATABASE IF NOT EXISTS IDENTIFIER('<DATABASE>');
CREATE SCHEMA IF NOT EXISTS IDENTIFIER('<DATABASE>.<SCHEMA>');

-- 3. Base usage grants on Database and Schema
GRANT USAGE ON DATABASE IDENTIFIER('<DATABASE>') TO ROLE IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');
GRANT USAGE ON DATABASE IDENTIFIER('<DATABASE>') TO ROLE IDENTIFIER('<LANGFLOW_DEVELOPER_ROLE>');
GRANT USAGE ON DATABASE IDENTIFIER('<DATABASE>') TO ROLE IDENTIFIER('<LANGFLOW_VIEWER_ROLE>');
GRANT USAGE ON DATABASE IDENTIFIER('<DATABASE>') TO ROLE IDENTIFIER('<LANGFLOW_AUTOMATION_ROLE>');

GRANT USAGE ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>') TO ROLE IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');
GRANT USAGE ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>') TO ROLE IDENTIFIER('<LANGFLOW_DEVELOPER_ROLE>');
GRANT USAGE ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>') TO ROLE IDENTIFIER('<LANGFLOW_VIEWER_ROLE>');
GRANT USAGE ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>') TO ROLE IDENTIFIER('<LANGFLOW_AUTOMATION_ROLE>');

-- 4. Governed Object Creation Privileges (granted ONLY to Developer/Admin, never Viewer)
GRANT CREATE TABLE, CREATE HYBRID TABLE, CREATE DYNAMIC TABLE, CREATE STAGE
    ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>')
    TO ROLE IDENTIFIER('<LANGFLOW_DEVELOPER_ROLE>');

GRANT ALL PRIVILEGES ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>')
    TO ROLE IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');

-- 5. Snowflake Artifact Repository PyPI access for Python Interpreter (REQ-12)
GRANT DATABASE ROLE SNOWFLAKE.PYPI_REPOSITORY_USER
    TO ROLE IDENTIFIER('<LANGFLOW_DEVELOPER_ROLE>');

-- 6. Caller Grants for SPCS executeAsCaller (ADR-003)
GRANT CALLER USAGE ON DATABASE IDENTIFIER('<DATABASE>')
    TO ROLE IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');
GRANT CALLER USAGE ON SCHEMA IDENTIFIER('<DATABASE>.<SCHEMA>')
    TO ROLE IDENTIFIER('<LANGFLOW_ADMIN_ROLE>');
